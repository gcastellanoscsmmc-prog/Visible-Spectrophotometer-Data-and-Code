# Load RGB images as floating-point arrays
def load_rgb(name):
    path = DATA_DIR / name

    if not path.is_file():
        raise FileNotFoundError(
            f'Image file not found: {path}'
        )

    with Image.open(path) as img:
        return np.asarray(
            img.convert('RGB'),
            dtype=np.float64
        )


# Convert RGB values into weighted luminance
def luminance(rgb):
    return (
        0.299 * rgb[..., 0]
        + 0.587 * rgb[..., 1]
        + 0.114 * rgb[..., 2]
    )


# Load the dark-reference image
dark = load_rgb('Dark_Camara_final.jpg')


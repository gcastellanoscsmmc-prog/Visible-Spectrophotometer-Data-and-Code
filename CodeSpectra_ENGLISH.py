from scipy.signal import find_peaks

# Use only the 30 ppm chlorophyllin calibration photographs acquired in ethanol.
#
# The independent chlorophyllin sweep is NOT used here.
# The reference is the mean of five ethanol blanks.

absorbance_30_replicates = []

for replicate in range(1, 4):

    I = spectrum_profile(
        corrected_samples[(30, replicate)]
    )

    T, A = calculate_absorbance(
        I,
        mean_blank_intensity,
        wavelengths
    )

    absorbance_30_replicates.append(A)

absorbance_30_replicates = np.asarray(
    absorbance_30_replicates
)

# Retain wavelengths with valid absorbance in all replicates.
valid_30 = (
    np.isfinite(wavelengths)
    & np.all(
        np.isfinite(absorbance_30_replicates),
        axis=0
    )
)

if np.count_nonzero(valid_30) < 21:
    raise ValueError(
        'Insufficient valid data for 30 ppm peak assessment.'
    )

peak_wavelengths = wavelengths[valid_30]
peak_pixels = pixels[valid_30]

replicate_values = absorbance_30_replicates[:, valid_30]

mean_30_absorbance = np.mean(
    replicate_values,
    axis=0
)

sd_30_absorbance = np.std(
    replicate_values,
    axis=0,
    ddof=1
)

# Smooth the mean spectrum for exploratory peak detection.
# Raw measurements remain unchanged.
smoothed_30_absorbance = savgol_filter(
    mean_30_absorbance,
    window_length=21,
    polyorder=2
)

# Estimate high-frequency fluctuations.
smoothing_residuals = (
    mean_30_absorbance - smoothed_30_absorbance
)

peak_noise = 1.4826 * np.median(
    np.abs(
        smoothing_residuals
        - np.median(smoothing_residuals)
    )
)

minimum_prominence = max(
    3 * peak_noise,
    1e-6
)

# Search around the absorption regions identified with the commercial spectrophotometer.
# The commercial maxima define search regions only.
peak_regions = {
    'Soret region': (385, 450),
    'Red region': (590, 650)
}

peak_records = []

for region, (lo, hi) in peak_regions.items():

    idx = np.flatnonzero(
        (peak_wavelengths >= lo)
        & (peak_wavelengths <= hi)
    )

    if len(idx) < 3:
        raise ValueError(
            f'Insufficient calibrated data in {region}.'
        )

    regional_profile = smoothed_30_absorbance[idx]

    peaks, properties = find_peaks(
        regional_profile,
        prominence=minimum_prominence,
        distance=8
    )

    accepted = []

    for j, local_peak in enumerate(peaks):

        position = idx[local_peak]

        # A candidate must show positive apparent absorbance in all three 30 ppm replicates.
        positive_replicates = np.all(
            replicate_values[:, position] > 0
        )

        # The mean signal must exceed twice the between-replicate standard deviation.
        reproducible_signal = (
            smoothed_30_absorbance[position]
            > 2 * sd_30_absorbance[position]
        )

        if (
            smoothed_30_absorbance[position] > 0
            and positive_replicates
            and reproducible_signal
        ):
            accepted.append(j)

    if accepted:

        best = max(
            accepted,
            key=lambda j: regional_profile[peaks[j]]
        )

        position = idx[peaks[best]]

        peak_records.append({
            'Region': region,
            'Peak_pixel': int(peak_pixels[position]),
            'Peak_wavelength_nm': float(
                peak_wavelengths[position]
            ),
            'Mean_apparent_absorbance': float(
                mean_30_absorbance[position]
            ),
            'SD_apparent_absorbance': float(
                sd_30_absorbance[position]
            ),
            'Peak_prominence': float(
                properties['prominences'][best]
            ),
            'Status': 'Exploratory candidate'
        })

    else:

        peak_records.append({
            'Region': region,
            'Peak_pixel': np.nan,
            'Peak_wavelength_nm': np.nan,
            'Mean_apparent_absorbance': np.nan,
            'SD_apparent_absorbance': np.nan,
            'Peak_prominence': np.nan,
            'Status': 'No reproducible positive peak detected'
        })



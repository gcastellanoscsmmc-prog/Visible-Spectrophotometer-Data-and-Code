# 14. SIGNAL LIMITATIONS AT COMMERCIAL ABSORPTION MAXIMA
# ============================================================

peak_qc_records = []

for name in QC_SAMPLES:

    table = sweep_tables[name]
    commercial_table = commercial_spectra[name]

    # Identify the recorded commercial absorption maximum.
    peak_index = commercial_table[
        'Commercial_absorbance'
    ].idxmax()

    peak_nm = float(
        commercial_table.loc[
            peak_index, 'Wavelength_nm'
        ]
    )

    # Evaluate the region within 2 nm of the commercial maximum.
    region = (
        common_wavelength_mask
        & (np.abs(wavelengths - peak_nm) <= 2)
    )

    I = table['Sample_intensity'].to_numpy(dtype=float)
    I0 = table['Reference_intensity'].to_numpy(dtype=float)
    A = table['Absorbance'].to_numpy(dtype=float)

    sample_saturated = qc_near_saturation_mask(
        DYES[name]
    )

    low_sample = region & (I <= QC_SIGNAL_FLOOR)
    low_reference = region & (I0 <= QC_SIGNAL_FLOOR)

    sample_saturation = region & sample_saturated
    reference_saturation = region & qc_water_mask

    invalid_absorbance = region & ~np.isfinite(A)

    eligible = (
        region
        & np.isfinite(A)
        & (I > QC_SIGNAL_FLOOR)
        & (I0 > QC_SIGNAL_FLOOR)
        & ~sample_saturated
        & ~qc_water_mask
    )

    peak_qc_records.append({
        'Substance': name,
        'Commercial_maximum_nm': peak_nm,
        'Positions_within_2nm': int(np.count_nonzero(region)),
        'Low_sample_signal_positions':
            int(np.count_nonzero(low_sample)),
        'Low_reference_signal_positions':
            int(np.count_nonzero(low_reference)),
        'Sample_near_saturation_positions':
            int(np.count_nonzero(sample_saturation)),
        'Reference_near_saturation_positions':
            int(np.count_nonzero(reference_saturation)),
        'Undefined_absorbance_positions':
            int(np.count_nonzero(invalid_absorbance)),
        'QC_eligible_positions':
            int(np.count_nonzero(eligible))
    })


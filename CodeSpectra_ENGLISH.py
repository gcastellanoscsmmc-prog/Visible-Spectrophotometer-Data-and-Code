# 13. SPECTRAL SIGNAL QUALITY ASSESSMENT
# ============================================================

# Identify potentially unreliable spectral positions caused by low digital intensity or near-saturation of JPEG pixels.
#
# These criteria are exploratory quality-control indicators.
# They do not correct exposure, validate absorbance, or establish instrument detection limits.
#
# Original spectra and numerical values remain unchanged.

QC_SATURATION_THRESHOLD = 250
QC_SIGNAL_FLOOR = 5.0
QC_SIGNAL_FLOOR_SENSITIVITY = [2.0, 5.0, 10.0]

QC_SAMPLES = [
    'Yellow 5',
    'Yellow 6',
    'Blue 1',
    'Algae chlorophyll',
    'Chlorophyllin'
]

# ------------------------------------------------------------
# DETECT NEAR-SATURATION IN THE ORIGINAL IMAGES
# ------------------------------------------------------------

def qc_near_saturation_mask(filename):

    original_image = load_rgb(filename)

    center_row = original_image.shape[0] // 2
    start_row = max(0, center_row - 5)
    end_row = min(original_image.shape[0], center_row + 6)

    region = original_image[start_row:end_row, :, :]

    # Mark a spectral position if at least one RGB value reaches the selected near-saturation threshold.
    return np.any(
        region >= QC_SATURATION_THRESHOLD,
        axis=(0, 2)
    )


qc_water_mask = qc_near_saturation_mask(
    DYES['Water']
)

# ------------------------------------------------------------
# EVALUATE SIGNAL QUALITY FOR EACH CHROMOPHORE
# ------------------------------------------------------------

qc_comparison_records = []
qc_sensitivity_records = []
qc_masked_spectra = {}

for name in QC_SAMPLES:

    table = sweep_tables[name]

    I = table['Sample_intensity'].to_numpy(dtype=float)
    I0 = table['Reference_intensity'].to_numpy(dtype=float)
    A = table['Absorbance'].to_numpy(dtype=float)

    sample_saturated = qc_near_saturation_mask(
        DYES[name]
    )

    # Preserve the mathematical validity criterion.
    mathematical_valid = (
        common_wavelength_mask
        & np.isfinite(I)
        & np.isfinite(I0)
        & np.isfinite(A)
        & (I > 0)
        & (I0 > 0)
    )

    # Conservatively flag positions with near-saturated pixels in either the blank or the sample image.
    saturation_acceptable = (
        ~qc_water_mask
        & ~sample_saturated
    )

    total_positions = int(
        np.count_nonzero(common_wavelength_mask)
    )

    # Examine sensitivity to the selected signal floor.
    for floor in QC_SIGNAL_FLOOR_SENSITIVITY:

        eligible = (
            mathematical_valid
            & saturation_acceptable
            & (I > floor)
            & (I0 > floor)
        )

        n_eligible = int(np.count_nonzero(eligible))

        qc_sensitivity_records.append({
            'Substance': name,
            'Signal_floor_digital_units': floor,
            'Eligible_positions': n_eligible,
            'Eligible_percent':
                100 * n_eligible / total_positions
        })

    # Primary exploratory quality-control mask.
    qc_valid = (
        mathematical_valid
        & saturation_acceptable
        & (I > QC_SIGNAL_FLOOR)
        & (I0 > QC_SIGNAL_FLOOR)
    )

    # Do not modify the underlying measured absorbance.
    # NaN is used only to hide flagged positions in the quality-control visualization.
    qc_masked_spectra[name] = np.where(
        qc_valid,
        A,
        np.nan
    )

    eligible_wavelengths = wavelengths[qc_valid]

    commercial_table = commercial_spectra[name]

    commercial_peak_index = (
        commercial_table['Commercial_absorbance'].idxmax()
    )

    commercial_peak_nm = float(
        commercial_table.loc[
            commercial_peak_index,
            'Wavelength_nm'
        ]
    )

    # Check whether quality-controlled DIY data exist within 2 nm of the commercial absorbance maximum.
    data_near_peak = bool(
        np.any(
            qc_valid
            & (np.abs(wavelengths - commercial_peak_nm) <= 2)
        )
    )

    n_eligible = int(np.count_nonzero(qc_valid))

    qc_comparison_records.append({
        'Substance': name,
        'Calibrated_positions': total_positions,
        'Mathematically_valid_positions':
            int(np.count_nonzero(mathematical_valid)),
        'QC_eligible_positions': n_eligible,
        'QC_eligible_percent':
            100 * n_eligible / total_positions,
        'Minimum_eligible_wavelength_nm':
            float(np.min(eligible_wavelengths))
            if n_eligible else np.nan,
        'Maximum_eligible_wavelength_nm':
            float(np.max(eligible_wavelengths))
            if n_eligible else np.nan,
        'Commercial_maximum_nm': commercial_peak_nm,
        'QC_data_near_commercial_maximum': data_near_peak
    })



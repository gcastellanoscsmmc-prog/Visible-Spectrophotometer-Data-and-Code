# ------------------------------------------------------------
# IDENTIFY SAMPLE NAMES FROM CSV FILENAMES
# ------------------------------------------------------------

def identify_commercial_sample(filename):

    name = unicodedata.normalize(
        'NFKD', filename
    ).encode(
        'ascii', 'ignore'
    ).decode('ascii').lower()

    name = re.sub(r'[^a-z0-9]+', ' ', name)
    name = ' '.join(name.split())

    if 'jamaica' in name or 'hibiscus' in name:
        return None

    if 'clorofilina' in name or 'chlorophyllin' in name:
        return 'Chlorophyllin'

    if 'clorofila' in name or 'chlorophyll' in name:
        return 'Algae chlorophyll'

    if 'amarillo 5' in name or 'yellow 5' in name:
        return 'Yellow 5'

    if 'amarillo 6' in name or 'yellow 6' in name:
        return 'Yellow 6'

    if 'azul 1' in name or 'blue 1' in name:
        return 'Blue 1'

    return None


# ------------------------------------------------------------
# READ THE COMMERCIAL SPECTRAL CSV FORMAT
# ------------------------------------------------------------

def read_commercial_csv(path):

    # The COMMERCIAL export contains instrument metadata before the spectral data header.

    text = None
    encoding_used = None

    for encoding in ('utf-8-sig', 'cp1252', 'latin-1'):
        try:
            text = path.read_text(encoding=encoding)
            encoding_used = encoding
            break
        except UnicodeDecodeError:
            continue

    if text is None:
        raise ValueError(
            f'Unable to decode commercial file: {path.name}'
        )

    lines = text.splitlines()
    header_line = None

    for i, line in enumerate(lines):

        normalized_header = re.sub(
            r'\s+', '', line.lower()
        )

        if normalized_header.startswith(
            'wl(nm),abs,t%'
        ):
            header_line = i
            break

    if header_line is None:
        raise ValueError(
            f'Commercial spectral header not found in {path.name}. '
            'Expected: WL(nm), Abs, T%'
        )

    table = pd.read_csv(
        path,
        skiprows=header_line,
        encoding=encoding_used
    )

    if table.shape[1] < 3:
        raise ValueError(
            f'Insufficient spectral columns: {path.name}'
        )

    # Preserve the original numerical data.
    table = table.iloc[:, :3].copy()

    table.columns = [
        'Wavelength_nm',
        'Commercial_absorbance',
        'Commercial_transmittance_percent'
    ]

    for column in table.columns:
        table[column] = pd.to_numeric(
            table[column],
            errors='raise'
        )

    if not np.all(
        np.isfinite(table.to_numpy(dtype=float))
    ):
        raise ValueError(
            f'Non-finite spectral values in {path.name}'
        )

    if table['Wavelength_nm'].duplicated().any():
        raise ValueError(
            f'Duplicate wavelength values in {path.name}'
        )

    table = table.sort_values(
        'Wavelength_nm'
    ).reset_index(drop=True)

    return table



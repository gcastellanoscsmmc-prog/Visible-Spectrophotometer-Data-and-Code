# Subtract the dark-reference image
def subtract_dark(name):
    image = load_rgb(name)

    if image.shape != dark.shape:
        raise ValueError(
            f'Incompatible image dimensions for {name}: '
            f'{image.shape} vs {dark.shape}'
        )

    # Preserve negative values for diagnostic purposes
    return image - dark


# Extract a spectral intensity profile
def spectrum_profile(rgb, channel='L'):

    if rgb.ndim != 3 or rgb.shape[2] != 3:
        raise ValueError(
            'Expected an RGB image with three color channels.'
        )

    if channel not in ('L', 'R', 'G', 'B'):
        raise ValueError(
            'Channel must be L, R, G, or B.'
        )

    # Average 11 central rows to reduce pixel-level noise
    row = rgb.shape[0] // 2

    start_row = max(0, row - 5)
    end_row = min(rgb.shape[0], row + 6)

    region = rgb[start_row:end_row, :, :]

    if channel == 'L':
        return luminance(region).mean(axis=0)

    return region[:, :, 'RGB'.index(channel)].mean(axis=0)


# Calculate transmittance and apparent absorbance
def calculate_absorbance(intensity, blank, wavelengths):

    intensity = np.asarray(intensity, dtype=float)
    blank = np.asarray(blank, dtype=float)
    wavelengths = np.asarray(wavelengths, dtype=float)

    if (
        intensity.ndim != 1
        or blank.ndim != 1
        or wavelengths.ndim != 1
    ):
        raise ValueError(
            'Spectral profiles must be one-dimensional arrays.'
        )

    if (
        len(intensity) != len(blank)
        or len(intensity) != len(wavelengths)
    ):
        raise ValueError(
            'Spectral profiles have different lengths.'
        )

    A = np.full(len(intensity), np.nan, dtype=float)
    T = np.full(len(intensity), np.nan, dtype=float)

    # Only calculate ratios for valid positive signals
    valid = (
        np.isfinite(intensity)
        & np.isfinite(blank)
        & (intensity > 0)
        & (blank > 0)
        & np.isfinite(wavelengths)
        & (wavelengths >= CAL_MIN)
        & (wavelengths <= CAL_MAX)
    )

    T[valid] = intensity[valid] / blank[valid]
    A[valid] = -np.log10(T[valid])

    return T, A


